const npcDropRows = [];
for (const [id, list] of Object.entries(npcLoot)) {
  const keep = [];
  for (const [item, p, quest] of list) {
    const isGear = gearIds.has(item);
    const q = isGear ? itemById.get(item).q : minorById.get(item)?.[1] ?? -1;
    if (q < 0) continue;
    if (quest) keep.push([item, p, 1]);
    else if (isGear ? q >= 2 && p >= 0.5 : q >= 3 && p >= 0.5) keep.push([item, p, 0]);
  }
  keep.sort((a, b) => b[2] - a[2] || b[1] - a[1]);
  if (keep.length) npcDropRows.push([Number(id), keep.slice(0, 4).map(([i, p, q]) => `${i}:${Math.round(p * 100) / 100}${q ? ':q' : ''}`).join(';')]);
}

