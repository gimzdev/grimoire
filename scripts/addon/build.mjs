// Sections that are about the site itself.
const SITE_SECTIONS = { 'talents-overview': ['Using the calculator'] };

function parseGuide(file) {
  const slug = path.basename(file, '.md');
  let raw = readFileSync(file, 'utf8').replace(/\r/g, '');
  for (const [from, to] of IN_GAME[slug] ?? []) {
    if (raw.split(from).length !== 2) console.warn(`  guide ${slug}: the add-on's rewrite of "${from.slice(0, 60)}" no longer matches; update IN_GAME in scripts/addon/build.mjs`);
    else raw = raw.replace(from, () => to);
  }
  for (const title of SITE_SECTIONS[slug] ?? []) {
    const lines = raw.split('\n');
    const at = lines.findIndex((l) => new RegExp(`^#{2,4}\\s+${title}\\s*$`).test(l));
    if (at < 0) {
      console.warn(`  guide ${slug}: no section "${title}" to leave out`);
      continue;
    }
    const level = lines[at].match(/^#+/)[0].length;
    let end = at + 1;
    while (end < lines.length && !(lines[end].match(/^#+\s/) && lines[end].match(/^#+/)[0].length <= level)) end++;
    lines.splice(at, end - at);
    raw = lines.join('\n');
  }
  const fm = raw.match(/^---\n([\s\S]*?)\n---\n/);
  const front = {};
  if (fm) for (const line of fm[1].split('\n')) {
    const m = line.match(/^([a-z]+):\s*(.*)$/);
    if (m) front[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  const body = fm ? raw.slice(fm[0].length) : raw;
  const blocks = [];
  let para = [];
  let table = [];
  const flushPara = () => {
    if (para.length) blocks.push(['p', inline(para.join(' '))]);
    para = [];
  };
  const flushTable = () => {
    if (!table.length) return;
    const rows = table.filter((r) => !/^\|?\s*:?-{2,}/.test(r)).map((r) => r.replace(/^\||\|$/g, '').split('|').map((c) => c.trim()));
    const [header, ...rest] = rows;
    // Two columns read as a label and its value; wider tables name each value by its column.
    const wide = header.length > 2;
    for (const r of rest) {
      const label = inline(r[0]);
      const cells = r.slice(1).map((c, i) => (c ? `${wide && header[i + 1] ? `|cffa29d93${inline(header[i + 1])}:|r ` : ''}${inline(c)}` : '')).filter(Boolean);
      blocks.push(['row', label, cells.join('\n')]);
    }
    table = [];
  };
  for (const line of body.split('\n')) {
    const l = line.trimEnd();
    if (/^\s*\|/.test(l)) {
      flushPara();
      table.push(l.trim());
      continue;
    }
    flushTable();
    if (!l.trim()) {
      flushPara();
      continue;
    }
    let m;
    if ((m = l.match(/^(#{2,4})\s+(.*)$/))) {
      flushPara();
      blocks.push([m[1].length === 2 ? 'h' : 'h3', inline(m[2])]);
    } else if ((m = l.match(/^\s*\[\[build:([^\]]+)\]\]\s*$/))) {
      flushPara();
      if (buildById.has(m[1])) blocks.push(['build', m[1]]);
    } else if ((m = l.match(/^\s*[-*]\s+\[([^\]]+)\]\(\/tools\/legacy\?tab=perks&p=([0-9A-Za-z]+)\):\s*(.*)$/))) {
      // A Legacy plan to start from: a card that loads it on the Legacy page. Guides only link Grimoire's own builds,
      // whose codes the data build has checked against the perk rules.
      if (!legacy.builds.some((b) => b.code === m[2])) throw new Error(`${slug}: the plan link ${m[2]} is none of Grimoire's Legacy builds.`);
      flushPara();
      blocks.push(['plan', m[2], inline(m[1]), inline(m[3])]);
    } else if ((m = l.match(/^\s*[-*]\s+(.*)$/))) {
      flushPara();
      blocks.push(['li', inline(m[1])]);
    } else if ((m = l.match(/^\s*(\d+)\.\s+(.*)$/))) {
      flushPara();
      blocks.push(['ol', inline(m[2]), Number(m[1])]);
    } else para.push(l.trim());
  }
  flushPara();
  flushTable();
  return {
    slug,
    title: txt(front.title ?? slug),
    desc: txt(front.description ?? ''),
    category: txt(front.category ?? 'Guides'),
    icon: front.icon,
    order: Number(front.order ?? 99),
    blocks,
  };
}
