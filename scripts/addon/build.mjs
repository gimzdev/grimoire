// A step is { kind, a, b, area, x, y, level, c }: kind 1 accept (a quest, b giver), 2 turn in (a quest, b ender),
// 3 do objectives (a quest, b a bit per objective, c the target), 4 go to a zone (a zone), 5 fly (a from node, b to
// node), 6 boat (a transport), 7 learn a flight path (a node), 8 train (a the trainer), 9 grind (a level, b mob, c the
// mob's level), 10 use the Hearthstone (to area, x, y), 11 bind the Hearthstone (a innkeeper), 12 cast a class
// teleport (a the spell, to area, x, y). Givers, enders and targets are creature ids, or minus an object id.
//
// There is a route for every race and class, so each route's steps are one string, read into steps only when the
// route is opened (Guide.lua): steps split by ";", each a kind letter then its fields a, b, area, x, y, level and c in
// base 36, split by ","; x and y in tenths of a percent, "~" before a negative number, an empty field for 0.
const STEP_KIND = { A: 1, T: 2, C: 3, Z: 4, F: 5, B: 6, P: 7, R: 8, L: 9, H: 10, N: 11, S: 12 };
const transportIds = Object.keys(guide.transports);
function guideStep(s) {
  const k = STEP_KIND[s[0]];
  switch (s[0]) {
    case 'A':
    case 'T':
    case 'F':
      return [k, s[1], s[2], s[3], s[4], s[5], s[6]];
    case 'L': {
      // The mob's level, for the kills the guide works out are left.
      const n = s[2] ? npcs[s[2]] : null;
      return n ? [k, s[1], s[2], s[3], s[4], s[5], s[6], Math.round((n[2] + n[3]) / 2)] : [k, s[1], s[2], s[3], s[4], s[5], s[6]];
    }
    case 'C':
      return [k, s[1], s[2].reduce((m, i) => m + 2 ** i, 0), s[3], s[4], s[5], s[6], s[7]];
    case 'B':
      return [k, transportIds.indexOf(s[1]) + 1, 0, s[2], s[3], s[4], s[5]];
    case 'Z':
    case 'P':
    case 'R':
    case 'H':
    case 'N':
    case 'S':
      return [k, s[1], 0, s[2], s[3], s[4], s[5]];
    default:
      throw new Error(`guide step ${s[0]}`);
  }
}
const KIND_LETTER = Object.fromEntries(Object.entries(STEP_KIND).map(([letter, k]) => [k, letter]));
const b36 = (n) => {
  if (!Number.isInteger(n)) throw new Error(`guide: ${n} is no whole number`);
  return n === 0 ? '' : n < 0 ? `~${(-n).toString(36)}` : n.toString(36);
};
function encodeStep(s) {
  const [k, a, b, area, x, y, level, c] = guideStep(s);
  const fields = [a, b, area, Math.round(x * 10), Math.round(y * 10), level];
  if (c) fields.push(c);
  return KIND_LETTER[k] + fields.map(b36).join(',').replace(/,+$/, '');
}
