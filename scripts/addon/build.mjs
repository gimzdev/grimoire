function pct(p) {
  if (p >= 10) return `${Math.round(p)}%`;
  if (p >= 1) return `${p.toFixed(1)}%`;
  if (p >= 0.01) return `${p.toFixed(2)}%`;
  return 'under 0.01%';
}

/** The site's sourceSummary: the first source in plain words, with its drop chance. */
function gearSource(it) {
  const codes = it.src ?? [];
  let line;
  for (const s of it.sm ?? []) {
    const zone = s.z ? zoneName(s.z) : undefined;
    const where = zone && zone !== s.n ? ` (${zone})` : '';
    if (s.t === 1) {
      const vendor = codes.includes(5) && !codes.includes(2);
      line = `${vendor ? 'Vendor' : 'Drop'}: ${s.n ?? 'Unknown'}${where}`;
      if (vendor) {
        // Sold by each side's merchants: a line for each side, the Alliance's first (the add-on shows yours).
        const list = vendors[it.i] ?? [];
        const sells = (side) => list.find((v) => (npcs[String(v)]?.[5] ?? 'hh')[side] !== 'h');
        const a = sells(0);
        const h = sells(1);
        const at = (v) => {
          const n = npcs[String(v)];
          const z = n?.[6] ? zoneName(n[6]) : undefined;
          return `Vendor: ${n?.[0] ?? 'Unknown'}${z && z !== n?.[0] ? ` (${z})` : ''}`;
        };
        if (a && h && a !== h) line = `${at(a)}\n${at(h)}`;
      }
      if (!vendor) {
        const d = drops[it.i];
        const match = d?.s.find((x) => x[0] === 'n' && x[1] === s.id) ?? (d?.s.length === 1 ? d.s[0] : undefined);
        if (match) line += `, ${pct(match[2])}`;
      }
    } else if (s.t === 5) line = `Quest: ${s.n ?? 'Quest'}${where}`;
    else if (s.t === 2) line = `Container: ${s.n ?? 'Object'}${where}`;
    else if (s.t === 6) line = `Crafted: ${s.s ? wow.PROFESSION[s.s] ?? 'Profession' : 'Profession'}`;
    else if (s.t === 3) line = `Contained in: ${s.n ?? 'an item'}`;
    else if (s.t === 7) line = `Made from: ${s.n ?? 'an item'}`;
    else if (s.z && !s.n) line = `${codes.includes(2) ? 'Drop' : wow.SOURCE[codes[0]] ?? 'Source'}: ${zone ?? 'Unknown zone'}`;
    if (line) break;
  }
  if (!line && codes.length) line = { 1: 'Crafted', 2: 'World drop', 3: 'PvP reward', 4: 'Quest reward', 5: 'Sold by a vendor' }[codes[0]];
  return line ?? '';
}

