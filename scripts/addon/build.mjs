// data/encounters.json (scripts/data/lib/encounters.mjs): the bosses of every Classic dungeon and raid in run order.
// Abilities go out as spell id, their whole text (the data keeps it short), when it is cast, which creature of the
// encounter casts it and, for a spell aimed at the boss's own creatures, their names. Names and schools of the spells
// sit in one table.
const encounters = J('encounters.json');
const known = (id) => itemById.has(id) || minorById.has(id);
const bossSpells = new Map(); // id -> [name, school]
const dungeonNpcs = new Map(); // creatures the trash lists name -> name
// A chance per kill to two decimals; one under 0.01% keeps its first figures (Nefarian's recipes, 0.0013%), so the
// add-on can say "<0.01%" instead of 0.
const r2 = (p) => (p > 0 && p < 0.01 ? Math.max(0.0001, Number(p.toPrecision(2))) : Math.round(p * 100) / 100);
const npcNameOf = (id) => encounters.npcs[id] ?? `NPC ${id}`;

function encounterRows(slug) {
  const e = encounters.dungeons[slug];
  if (!e) return {};
  const wingNames = e.wings.map((w) => w.name ?? '');
  const named = wingNames.some(Boolean);
  const bosses = [];
  e.wings.forEach((w, wi) => {
    for (const b of w.bosses) {
      const main = b.npcs[0];
      const index = (id) => b.npcs.findIndex((n) => n.id === id) + 1;
      for (const a of b.abilities) if (!bossSpells.has(a.id)) bossSpells.set(a.id, [txt(a.n), a.s]);
      const event = b.npcs.find((n) => n.ev)?.ev;
      bosses.push({
        n: txt(b.n),
        id: main.id,
        lo: main.lv[0],
        hi: main.lv[1],
        r: main.r,
        w: named ? wi + 1 : undefined,
        f: b.f?.length ? b.f.join(',') : undefined,
        ev: event ? txt(event) : undefined,
        note: b.note ? txt(b.note) : undefined,
        npcs: b.npcs.length > 1 ? b.npcs.map((n) => [n.id, txt(n.n), n.lv[0], n.lv[1]]) : undefined,
        // id, text, when, caster (its place in npcs), and the boss's creatures it is cast on
        ab: b.abilities.map((a) => {
          const row = [a.id, txt(a.d ?? ''), txt(a.t ?? ''), a.by ? index(a.by) : 0];
          if (a.on?.length) row.push(txt([...new Set(a.on.map(npcNameOf))].join(', ')));
          return row;
        }),
        calls: b.summons?.length ? b.summons.map((x) => txt(`Calls ${x.n}${x.c > 1 ? ` (${x.c})` : ''}${x.t ? ` ${x.t}` : ''}.`)) : undefined,
        flees: b.flees ? txt(b.flees) : undefined,
        chest: b.chest ? txt(b.chest.n) : undefined,
        // item:chance[:flags[:from]]: flags 1 quest item, 2 recipe, 4 starts a quest; from the creature's place in npcs, 0 the chest
        loot: b.loot
          .filter(([i]) => known(i))
          .map(([i, p, f, from]) => `${i}:${r2(p)}${f || from ? `:${f}` : ''}${from ? `:${from < 0 ? 0 : index(from)}` : ''}`)
          .join(';'),
      });
    }
  });
  for (const t of e.trash) for (const [n] of t.by) dungeonNpcs.set(n, txt(encounters.npcs[n] ?? `NPC ${n}`));
  return {
    map: e.map,
    count: e.bosses,
    rares: e.rares || undefined,
    wings: named ? wingNames.map(txt) : undefined,
    // each wing is a run of its own (Scarlet Monastery, Blackrock Spire, Dire Maul): bosses are numbered per wing
    runs: e.runs ? true : undefined,
    bosses,
    // item:chance:npc,npc,...:more
    trash: e.trash
      .filter((t) => known(t.i))
      .map((t) => `${t.i}:${r2(t.p)}:${t.by.map(([n]) => n).join(',')}:${t.more ?? 0}`)
      .join(';'),
  };
}

