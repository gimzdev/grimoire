const KEYWORDS = new Set('and break do else elseif end false for function if in local nil not or repeat return then true until while'.split(' '));
const str = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '').replace(/\n/g, '\\n')}"`;
/** Text shown in the game: a lone "|" would start an escape sequence, so it is doubled. */
const txt = (s) => String(s ?? '').replace(/\|/g, '||');
function lua(v) {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : String(Math.round(v * 100) / 100);
  if (typeof v === 'string') return str(v);
  if (Array.isArray(v)) return `{${v.map(lua).join(',')}}`;
  const parts = [];
  for (const [k, x] of Object.entries(v)) {
    if (x === undefined || x === null) continue;
    const key = /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) && !KEYWORDS.has(k) ? k : /^-?\d+$/.test(k) ? `[${k}]` : `[${str(k)}]`;
    parts.push(`${key}=${lua(x)}`);
  }
  return `{${parts.join(',')}}`;
}
