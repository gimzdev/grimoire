function inline(s) {
  let t = txt(s);
  t = t.replace(/\[\[([a-z]+):([^\]]+)\]\]/g, (m, kind, rest) => {
    const parts = rest.split(':');
    if (kind === 'talent' || kind === 'ability') return `|cff${SPELL}${parts.slice(1).join(':')}|r`;
    if (kind === 'racial') return `|cff${SPELL}${rest}|r`;
    if (kind === 'class') {
      const c = classBySlug.get(rest);
      return c ? `|cff${c.color.replace('#', '')}${c.name}|r` : rest;
    }
    if (kind === 'quest') {
      const q = questById.get(Number(rest));
      return q ? `|cff${GOLD}${txt(q.n)}|r` : '';
    }
    if (kind === 'item') {
      const it = itemById.get(Number(rest));
      const m2 = minor[rest];
      const name = it?.n ?? m2?.[0];
      return name ? `|cff${QUALITY_HEX[it?.q ?? m2?.[1] ?? 1]}${txt(name)}|r` : '';
    }
    if (kind === 'spell') return spellNameById.has(Number(rest)) ? `|cff${SPELL}${spellNameById.get(Number(rest))}|r` : '';
    if (kind === 'build') {
      const b = buildById.get(rest);
      return b ? `|cff${GOLD}${txt(b.name)}|r` : '';
    }
    return '';
  });
  t = t.replace(/\*\*([^*]+)\*\*/g, `|cff${WHITE}$1|r`);
  t = t.replace(/(^|[^\w])_([^_]+)_(?=[^\w]|$)/g, '$1$2').replace(/(^|[^*])\*([^*]+)\*(?!\*)/g, '$1$2');
  // Links to the site's pages read as plain words in game.
  t = t.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '$1');
  t = t.replace(/`([^`]+)`/g, '$1');
  return t.trim();
}

