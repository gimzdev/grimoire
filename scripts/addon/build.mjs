/** A non-gear item's first source: its best drop, a quest that rewards it, or a vendor. */
function minorSource(id) {
  const d = drops[id];
  if (d?.s.length) {
    const top = [...d.s].sort((a, b) => b[2] - a[2])[0];
    const rec = top[0] === 'o' ? objects[top[1]] : top[0] === 'n' || top[0] === 'p' || top[0] === 's' ? npcs[top[1]] : undefined;
    if (rec) {
      const zone = zoneName(rec[top[0] === 'o' ? 1 : 6]);
      const what = top[0] === 'o' ? 'Container' : top[0] === 'p' ? 'Pickpocket' : top[0] === 's' ? 'Skinning' : 'Drop';
      return `${what}: ${rec[0]}${zone && zone !== rec[0] ? ` (${zone})` : ''}, ${pct(top[2])}`;
    }
    if (top[0] === 'f') return `Fishing${zoneName(top[1]) ? `: ${zoneName(top[1])}` : ''}`;
    if (top[0] === 'i') return `Contained in: ${minor[top[1]]?.[0] ?? itemById.get(top[1])?.n ?? 'an item'}`;
  }
  const q = rewardedBy.get(Number(id));
  if (q) return `Quest: ${q.n}`;
  const v = vendors[id];
  if (v?.length) {
    const n = npcs[v[0]];
    if (n) return `Vendor: ${n[0]}${zoneName(n[6]) ? ` (${zoneName(n[6])})` : ''}${v.length > 1 ? `, and ${v.length - 1} more` : ''}`;
  }
  return '';
}

