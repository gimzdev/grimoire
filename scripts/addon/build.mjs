const QUALITY_HEX = ['9d9d9d', 'ffffff', '1eff00', '2b8cff', 'b45cf7', 'ff8a1f', 'e6cc80'];
const SPELL = '9cc9f5';
const GOLD = 'ffd47a';
const WHITE = 'f4f1ea';
