// The classes an item is meant for, as a bit per class in CLASS_ORDER (0: no restriction): the item's own class list,
// or the classes of the quests that are its only source (the four Atiesh staves, class quest rewards).
const questsRewarding = new Map();
for (const q of quests) for (const [id] of [...(q.ir ?? []), ...(q.ic ?? [])]) {
  if (!questsRewarding.has(id)) questsRewarding.set(id, []);
  questsRewarding.get(id).push(q);
}
function classOnly(it) {
  let ids = it.cls ?? 0;
  if (!ids) {
    const qs = questsRewarding.get(it.i) ?? [];
    const onlyQuests = (it.src ?? []).every((c) => c === 4) && (it.sm ?? []).every((s) => s.t === 5);
    if (qs.length && onlyQuests && qs.every((q) => q.rc)) ids = qs.reduce((m, q) => m | q.rc, 0);
  }
  if (!ids) return 0;
  let m = 0;
  CLASS_ORDER.forEach((cls, i) => {
    const id = classBySlug.get(cls)?.id;
    if (id && ids & (1 << (id - 1))) m += 2 ** i;
  });
  return m === 2 ** CLASS_ORDER.length - 1 ? 0 : m;
}

// Classic's class mask (a bit per class id) as a bit per class in CLASS_ORDER; 0 for every class.
function classBits(ids) {
  if (!ids) return 0;
  let m = 0;
  CLASS_ORDER.forEach((cls, i) => {
    const id = classBySlug.get(cls)?.id;
    if (id && ids & (1 << (id - 1))) m += 2 ** i;
  });
  return m === 2 ** CLASS_ORDER.length - 1 ? 0 : m;
}

// Which classes can use an item, as a bit per class in CLASS_ORDER.
function usableMask(it, only) {
  let m = 0;
  CLASS_ORDER.forEach((cls, i) => {
    if (itemsLib.usableBy(it, cls, classBySlug.get(cls)?.weapons ?? []) && (!only || only & (2 ** i))) m += 2 ** i;
  });
  return m;
}

// What an item gives, for the add-on's upgrade scores (Gear.lua), as letters and numbers in one string: s5a3t7 is 5
// Strength, 3 Agility and 7 Stamina. s a t i p: the five stats; r armor; b block value; d and v a weapon's damage per
// second and speed; then what its "Equip:" lines give: sp spell damage and healing, hl healing, ds df di dn da dh one
// school's damage (Shadow, Frost, Fire, Nature, Arcane, Holy), cr sc critical strike % (melee and ranged, spells), ht sh
// hit % (the same), ap ra fa attack power (any, ranged, feral forms), m5 h5 mana and health every 5 seconds, de defense,
// dg pa bk dodge, parry and block %, pe spell penetration, wk weapon skill; pr 1 for a chance on hit.
const STAT_KEYS = { str: 's', agi: 'a', sta: 't', int: 'i', spi: 'p' };
const EFFECTS = [
  [/^Equip: Increases damage and healing done by magical spells and effects by up to (\d+)\.$/, 'sp'],
  [/^Equip: Increases healing done by spells and effects by up to (\d+)\.$/, 'hl'],
  [/^Equip: Increases damage done by Shadow spells and effects by up to (\d+)\.$/, 'ds'],
  [/^Equip: Increases damage done by Frost spells and effects by up to (\d+)\.$/, 'df'],
  [/^Equip: Increases damage done by Fire spells and effects by up to (\d+)\.$/, 'di'],
  [/^Equip: Increases damage done by Nature spells and effects by up to (\d+)\.$/, 'dn'],
  [/^Equip: Increases damage done by Arcane spells and effects by up to (\d+)\.$/, 'da'],
  [/^Equip: Increases damage done by Holy spells and effects by up to (\d+)\.$/, 'dh'],
  [/^Equip: Improves your chance to get a critical strike by (\d+)%\.$/, 'cr'],
  [/^Equip: Improves your chance to get a critical strike with spells by (\d+)%\.$/, 'sc'],
  [/^Equip: Improves your chance to hit by (\d+)%\.$/, 'ht'],
  [/^Equip: Improves your chance to hit with spells by (\d+)%\.$/, 'sh'],
  [/^Equip: \+(\d+) Attack Power\.$/, 'ap'],
  [/^Equip: \+(\d+) ranged Attack Power\.$/, 'ra'],
  [/^Equip: \+(\d+) Attack Power in Cat, Bear, and Dire Bear forms only\.$/, 'fa'],
  [/^Equip: Restores (\d+) mana per (\d+) sec\.$/, 'm5', (n, s) => (n * 5) / s],
  [/^Equip: Restores (\d+) health (?:per|every) (\d+) sec\.$/, 'h5', (n, s) => (n * 5) / s],
  [/^Equip: Increased Defense \+(\d+)\.$/, 'de'],
  [/^Equip: Increases your chance to dodge an attack by (\d+)%\.$/, 'dg'],
  [/^Equip: Increases your chance to parry an attack by (\d+)%\.$/, 'pa'],
  [/^Equip: Increases your chance to block attacks with a shield by (\d+)%\.$/, 'bk'],
  [/^Equip: Increases the block value of your shield by (\d+)\.$/, 'b'],
  [/^Equip: Decreases the magical resistances of your spell targets by (\d+)\.$/, 'pe'],
  [/^Equip: Increased (?:Two-handed )?(?:Daggers|Swords|Axes|Maces|Bows|Guns|Crossbows|Staves|Polearms|Fist Weapons) \+(\d+)\.$/, 'wk'],
  [/^Chance on hit: /, 'pr', () => 1],
];
const num2 = (v) => String(Math.round(v * 10) / 10);
function itemStats(it) {
  const out = new Map();
  const add = (k, v) => v && out.set(k, (out.get(k) ?? 0) + v);
  for (const [k, v] of Object.entries(it.st ?? {})) if (STAT_KEYS[k]) add(STAT_KEYS[k], v);
  add('r', it.ar ?? 0);
  for (const line of it.wl ?? []) {
    const m = /^(\d+) Block$/.exec(line);
    if (m) add('b', Number(m[1]));
  }
  if (it.w && it.w[3] > 0) {
    add('d', it.w[3]);
    add('v', it.w[2]);
  }
  for (const line of it.fx ?? []) {
    for (const [re, key, f] of EFFECTS) {
      const m = re.exec(line);
      if (m) {
        add(key, f ? f(Number(m[1]), Number(m[2])) : Number(m[1]));
        break;
      }
    }
  }
  return [...out].map(([k, v]) => k + num2(v)).join('');
}

// The quests that give an item (reward or choice), up to two, so the add-on can say one is on your route.
const rewardQuests = new Map();
