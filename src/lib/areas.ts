/** Where something is fished: the water's name, and the zone around it when the water is a part of one. */
export function fishingPlace(area: number): { name: string; zone?: { id: number; name: string } } | null {
  const known = categoryName(area);
  if (known !== 'Unknown') return { name: known };
  const a = AREAS[area];
  if (!a) return null;
  const zone = categoryName(a[1]);
  return zone === 'Unknown' ? { name: a[0] } : { name: a[0], zone: { id: a[1], name: zone } };
}
